function rev411_package_guard()
%REV411_PACKAGE_GUARD Verify that the complete Rev.4.1.1 package is active.

root=fileparts(mfilename('fullpath'));

req={ ...
    'rev411_initial_admissibility_screen', ...
    'rev41_mc_params', ...
    'rev41_apply_sample', ...
    'rev41_run_one', ...
    'rev41_summarize', ...
    'run_rev411_monte_carlo_parallel'};

for k=1:numel(req)
    q=which(req{k});
    if isempty(q)
        error('Rev411:IncompletePackage', ...
            ['Missing required Rev.4.1.1 function: %s\n' ...
             'Do not mix Rev.4.1 and Rev.4.1.1 files. Use the complete ' ...
             'Rev.4.1.1 parallel package.'],req{k});
    end
    if length(q)<length(root) || ~strcmpi(q(1:length(root)),root)
        error('Rev411:Shadow', ...
            'Function %s resolves outside the active Rev.4.1.1 root: %s', ...
            req{k},q);
    end
end

R=rev41_mc_params();
if ~isfield(R,'initStrategy') || ~strcmp(R.initStrategy,'backup_feasible')
    error('Rev411:WrongRevision', ...
        ['Active rev41_mc_params.m is not Rev.4.1.1. ' ...
         'Expected initStrategy=backup_feasible.']);
end

fprintf('REV.4.1.1 package guard = PASS\n');
fprintf('root = %s\n',root);
end
