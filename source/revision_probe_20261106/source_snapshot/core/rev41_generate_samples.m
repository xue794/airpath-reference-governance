function S=rev41_generate_samples(R)
%REV41_GENERATE_SAMPLES Reproducible Rev.4.1 random ensemble.

rng(R.seed,'twister');

T=local_empty_sample();
S=repmat(T,R.N,1);

for k=1:R.N
    Q=T;
    Q.index=k;

    Q.massScale=1+R.massFrac*(2*rand-1);
    Q.inertiaScale=1+R.inertiaFrac*(2*rand(4,1)-1);
    Q.aeroScale=1+R.aeroFrac*(2*rand(45,1)-1);

    Q.servoTauScale=1+R.servoTauFrac*(2*rand(3,1)-1);
    Q.thrustTauScale=1+R.thrustTauFrac*(2*rand-1);

    Q.windMean=R.windMean0+R.windMeanHalfRange.*(2*rand(3,1)-1);
    aScale=R.windAmpScaleRange(1)+ ...
        diff(R.windAmpScaleRange)*rand(3,1);
    Q.windAmp=R.windAmp0.*aScale;
    oScale=R.windOmegaScaleRange(1)+ ...
        diff(R.windOmegaScaleRange)*rand(3,1);
    Q.windOmega=R.windOmega0.*oScale;
    Q.windPhase=2*pi*rand(3,1);

    Q.noiseScale=R.noiseScaleRange(1)+ ...
        diff(R.noiseScaleRange)*rand;
    Q.noiseFreqScale=R.noiseFreqScaleRange(1)+ ...
        diff(R.noiseFreqScaleRange)*rand(11,1);
    Q.noisePhase=2*pi*rand(11,1);

    Q.initPosition=R.initPosHalfRange.*(2*rand(3,1)-1);
    Q.initVgB=R.initVgBHalfRange.*(2*rand(3,1)-1);

    ax=randn(3,1);
    if norm(ax)<1e-12, ax=[1;0;0]; end
    ax=ax/norm(ax);
    Q.initAttitudeRotvec=ax*(R.initAttitudeMax*rand);

    Q.initOmega=R.initOmegaHalfRange.*(2*rand(3,1)-1);
    Q.initWhatError=R.initWhatHalfRange.*(2*rand(3,1)-1);

    Q.windPeakBound=norm(abs(Q.windMean)+abs(Q.windAmp));
    Q.aeroMaxDeviationPct=100*max(abs(Q.aeroScale-1));

    S(k)=Q;
end
end

function Q=local_empty_sample()
Q=struct( ...
    'index',0, ...
    'massScale',1, ...
    'inertiaScale',ones(4,1), ...
    'aeroScale',ones(45,1), ...
    'servoTauScale',ones(3,1), ...
    'thrustTauScale',1, ...
    'windMean',zeros(3,1), ...
    'windAmp',zeros(3,1), ...
    'windOmega',zeros(3,1), ...
    'windPhase',zeros(3,1), ...
    'noiseScale',1, ...
    'noiseFreqScale',ones(11,1), ...
    'noisePhase',zeros(11,1), ...
    'initPosition',zeros(3,1), ...
    'initVgB',zeros(3,1), ...
    'initAttitudeRotvec',zeros(3,1), ...
    'initOmega',zeros(3,1), ...
    'initWhatError',zeros(3,1), ...
    'windPeakBound',0, ...
    'aeroMaxDeviationPct',0);
end
