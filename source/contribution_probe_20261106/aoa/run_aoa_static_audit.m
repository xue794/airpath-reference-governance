function run_aoa_static_audit()
% Finite static comparison on the PREVIOUS fully retained exploration grid.
% No retuning, new trajectories, or post-hoc omission of inconvenient states.
here=fileparts(mfilename('fullpath'));
base='D:/Research/paper1_Submission/revision_probe_20261106/source_snapshot';
addpath([base '/core']);addpath([base '/W2E']);addpath(here);
old=load('D:/Research/paper1_Submission/endpoint_probe_20261106/static/static_endpoint_probe.mat');
R=rg_params();R.rhoB=.10;Q=w2b_options();
Rows=struct([]);FD=struct([]);State=struct([]);K=struct([]);
for k=1:numel(old.states)
 s=old.states(k);x=[s.V;0;0;s.nuV;s.nuGamma_deg*pi/180;s.nuChi_deg*pi/180];
 F=rg_feedforward(x,R);if ~F.rootInfo.bracket,continue;end
 A0=cp_aoa_rows(x,R,'A0',F.alpha);Am=cp_aoa_rows(x,R,'Am',F.alpha);
 C=rg_constraint_affine(x,R);R0=R;R0.DeltaN=0;C0=rg_constraint_affine(x,R0);
 f0=[C0.hNminus;C0.hNplus];fm=[C.hNminus;C.hNplus];
 State=[State;struct('state_id',k,'admitted',s.admitted,'V',s.V,'alpha_deg',F.alpha*180/pi, ...
  'A0_lower_margin_rad',A0.h(1),'A0_upper_margin_rad',A0.h(2), ...
  'Am_lower_margin_rad',Am.h(1),'Am_upper_margin_rad',Am.h(2), ...
  'Am_lower_boundary_deg',Am.alphaLower*180/pi,'Am_upper_boundary_deg',Am.alphaUpper*180/pi, ...
  'N0_lower_margin_N',f0(1),'N0_upper_margin_N',f0(2), ...
  'N10_lower_margin_N',fm(1),'N10_upper_margin_N',fm(2), ...
  'A0_state_set_match',all((A0.h>=-1e-12)==(f0>=-1e-9)), ...
  'Am_state_set_match',all((Am.h>=-1e-12)==(fm>=-1e-9)))]; %#ok<AGROW>
 if ~s.admitted,continue;end
 % Analytic derivatives against independent central differences of root-
 % evaluated h(x), for three fixed acceleration directions, two epsilons.
 testU=[0 0 0;1 .08 -.05;-.7 -.03 .07]';
 for im=1:2
  if im==1,A=A0;mode='A0';else,A=Am;mode='Am';end
  for iu=1:size(testU,2)
   u=testU(:,iu);dx=[x(4:6);u];analytic=A.c+A.G*u-R.kN*A.h;
   for ep=[1e-5 1e-6]
    Bp=cp_aoa_rows(x+ep*dx,R,mode);Bm=cp_aoa_rows(x-ep*dx,R,mode);
    numeric=(Bp.h-Bm.h)/(2*ep);e=numeric-analytic;
    FD=[FD;struct('state_id',k,'mode',mode,'direction',iu,'epsilon',ep, ...
     'analytic_lower',analytic(1),'numeric_lower',numeric(1), ...
     'analytic_upper',analytic(2),'numeric_upper',numeric(2), ...
     'max_abs_error',max(abs(e)),'scaled_error',max(abs(e)./(1+abs(analytic))))]; %#ok<AGROW>
   end
  end
 end
 rr=old.rows([old.rows.state_id]==k);ix=[1:13 16:17];O=Q;O.FeasibleStart=rg_backup_control(x,R);
 for j=1:numel(rr)
  r=rr(j);cc=[r.targetV;r.targetGamma_deg*pi/180;r.targetChi_deg*pi/180];u0=rg_nominal_control(x,cc,R);
  [uA0,D0]=w2b_qp3(u0,-[C.G(ix,:);A0.G],[C.c(ix);A0.c],Q.Scale,O);
  [uAm,Dm]=w2b_qp3(u0,-[C.G(ix,:);Am.G],[C.c(ix);Am.c],Q.Scale,O);
  uN0=[r.zero_uV;r.zero_uGamma;r.zero_uChi];uN10=[r.full_uV;r.full_uGamma;r.full_uChi];
  phiA0onN0=A0.c+A0.G*uN0;phiAmonN10=Am.c+Am.G*uN10;
  phiN0onA0=C0.c(14:15)+C0.G(14:15,:)*uA0;
  phiN10onAm=C.c(14:15)+C.G(14:15,:)*uAm;
  Rows=[Rows;struct('state_id',k,'target',r.target,'V',s.V, ...
   'nuV',s.nuV,'nuGamma_deg',s.nuGamma_deg,'nuChi_deg',s.nuChi_deg, ...
   'A0_success',D0.Success,'Am_success',Dm.Success, ...
   'A0_minus_N0_scaled_inf',norm((uA0-uN0)./Q.Scale,inf), ...
   'Am_minus_N10_scaled_inf',norm((uAm-uN10)./Q.Scale,inf), ...
   'A0_objective',.5*sum(((uA0-u0)./Q.Scale).^2),'N0_objective',.5*sum(((uN0-u0)./Q.Scale).^2), ...
   'Am_objective',.5*sum(((uAm-u0)./Q.Scale).^2),'N10_objective',.5*sum(((uN10-u0)./Q.Scale).^2), ...
   'min_A0_phi_at_N0',min(phiA0onN0),'min_Am_phi_at_N10',min(phiAmonN10), ...
   'min_N0_phi_at_A0',min(phiN0onA0),'min_N10_phi_at_Am',min(phiN10onAm), ...
   'A0_uV',uA0(1),'A0_uGamma',uA0(2),'A0_uChi',uA0(3), ...
   'Am_uV',uAm(1),'Am_uGamma',uAm(2),'Am_uChi',uAm(3), ...
   'max_KKT',max([D0.PrimalNormalized D0.StationarityNormalized D0.ComplementarityNormalized ...
                  Dm.PrimalNormalized Dm.StationarityNormalized Dm.ComplementarityNormalized]))]; %#ok<AGROW>
 end
 if mod(k,75)==0,fprintf('state %d: comparisons %d derivative checks %d\n',k,numel(Rows),numel(FD));end
end
assert(all([State.A0_state_set_match])&&all([State.Am_state_set_match]),'State-set mismatch');
assert(max([FD.max_abs_error])<1e-6,'Derivative check failed');
assert(all([Rows.A0_success])&&all([Rows.Am_success]),'QP failed');
Summary=struct('root_existing_states',numel(State),'admitted_states',sum([State.admitted]), ...
 'state_set_checks_all_pass',true,'finite_difference_checks',numel(FD), ...
 'max_derivative_abs_error',max([FD.max_abs_error]),'max_derivative_scaled_error',max([FD.scaled_error]), ...
 'QP_comparisons',numel(Rows),'QP_all_success',true,'maxKKT',max([Rows.max_KKT]), ...
 'A0_N0_different_over_1e8',sum([Rows.A0_minus_N0_scaled_inf]>1e-8), ...
 'Am_N10_different_over_1e8',sum([Rows.Am_minus_N10_scaled_inf]>1e-8), ...
 'max_A0_N0_scaled_difference',max([Rows.A0_minus_N0_scaled_inf]), ...
 'max_Am_N10_scaled_difference',max([Rows.Am_minus_N10_scaled_inf]), ...
 'A0_violation_at_N0_over1e8',sum([Rows.min_A0_phi_at_N0]<-1e-8), ...
 'Am_violation_at_N10_over1e8',sum([Rows.min_Am_phi_at_N10]<-1e-8), ...
 'N0_violation_at_A0_over1e8',sum([Rows.min_N0_phi_at_A0]<-1e-8), ...
 'N10_violation_at_Am_over1e8',sum([Rows.min_N10_phi_at_Am]<-1e-8));
writetable(struct2table(State),fullfile(here,'state_set_equivalence.csv'));
writetable(struct2table(FD),fullfile(here,'analytic_derivative_checks.csv'));
writetable(struct2table(Rows),fullfile(here,'aoa_QP_comparisons.csv'));
save(fullfile(here,'aoa_static_audit.mat'),'State','FD','Rows','Summary','R','Q');
f=fopen(fullfile(here,'aoa_static_summary.json'),'w');fprintf(f,'%s',jsonencode(Summary));fclose(f);
disp(Summary);fprintf('AOA_STATIC_AUDIT_DONE\n');
end
