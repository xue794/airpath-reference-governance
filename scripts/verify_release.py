"""Verify release hashes and selected saved-output summaries (Python 3.10+)."""
from pathlib import Path
import subprocess
import sys


def main() -> int:
    if sys.version_info < (3, 10):
        print("Python 3.10 or newer is required.", file=sys.stderr)
        return 2
    root = Path(__file__).resolve().parents[1]
    entries = ("check_manifest.py", "reproduce.py", "verify.py")
    for index, entry in enumerate(entries, 1):
        script = root / "python" / entry
        if not script.is_file():
            print(f"Missing release entry: {script}", file=sys.stderr)
            return 2
        print(f"[{index}/{len(entries)}] {entry}", flush=True)
        try:
            # Isolated mode ignores user-site modules and PYTHON* overrides.
            # No shell is used; absolute paths remain safe when they contain spaces.
            subprocess.run(
                [sys.executable, "-I", "-B", str(script)],
                cwd=root,
                check=True,
            )
        except subprocess.CalledProcessError as error:
            print(f"Stopped: {entry} exited with status {error.returncode}.", file=sys.stderr)
            return error.returncode or 1
        except OSError as error:
            print(f"Could not start {entry}: {error}", file=sys.stderr)
            return 1
    print("PASS: release hashes and selected saved-output summaries.")
    print("No MATLAB integration or interval proof was regenerated by this command.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
